const assert = require('node:assert/strict');
const render = require('../buletin-render.js');
const fs = require('node:fs'), path = require('node:path');
const b={tipe:'kaki',tombol:'Baca',url:'https://example.org/',sosial:'',hakcipta:'© Kartidaya'};
const defaults=render.sosial(b);
assert.equal(defaults.instagram,'https://www.instagram.com/kartidaya?igsh=ZDAxZ3FnemEwZG82');
assert.equal(defaults.facebook,'https://www.facebook.com/share/19ErEsRwRL/');
assert.equal(defaults.x,'');
assert.equal(defaults.website,'https://kartidaya.org/');
for(const name of ['instagram','facebook','website']) assert.ok(fs.statSync(path.join(__dirname,'..','vendor','buletin-'+name+'.png')).size>0);
let out=render({blok:[b]});
for(const name of ['Instagram','Facebook','Website']) assert.match(out.html,new RegExp('alt="'+name+'"'));
assert.match(out.html,/href="https:\/\/www\.instagram\.com\/kartidaya\?igsh=ZDAxZ3FnemEwZG82"/);
assert.match(out.html,/href="https:\/\/www\.facebook\.com\/share\/19ErEsRwRL\/"/);
assert.match(out.teks,/Website: https:\/\/kartidaya\.org\//);
assert.doesNotMatch(out.html,/alt="X"/,'ikon X tanpa alamat tidak tampil');
b.sosial={...defaults,x:'https://x.com/kartidaya'};
out=render({blok:[b]});
assert.match(out.html,/alt="X"/);
assert.ok(fs.statSync(path.join(__dirname,'..','vendor','buletin-x.png')).size>0);
assert.match(out.html,/href="https:\/\/x\.com\/kartidaya"/);
assert.match(out.teks,/X: https:\/\/x\.com\/kartidaya/);
b.sosial.instagram=''; out=render({blok:[b]});
assert.doesNotMatch(out.html,/buletin-instagram\.png/,'alamat kosong menyembunyikan ikon');
b.sosial={...defaults,instagram:'https://example.org/new?a=1&b=2'};
out=render({blok:[b]}); assert.match(out.html,/href="https:\/\/example\.org\/new\?a=1&amp;b=2"/);
assert.match(out.teks,/Instagram: https:\/\/example\.org\/new\?a=1&b=2/);
b.sosial.facebook='javascript:alert(1)'; out=render({blok:[b]}); assert.doesNotMatch(out.html,/href="javascript:/);
const old={tipe:'kaki',sosial:'Halo https://www.instagram.com/old/\nInfo https://x.com/lama\nWeb https://example.org/custom'};
assert.equal(render.sosial(old).instagram,'https://www.instagram.com/old/');
assert.equal(render.sosial(old).x,'https://x.com/lama');
assert.equal(render.sosial(old).website,'https://example.org/custom');
out=render({blok:[old]}); assert.match(out.teks,/Halo https:\/\/www\.instagram\.com\/old\//);
old.sosialLama=old.sosial; old.sosial=render.sosial(old);
out=render({blok:[old]}); assert.match(out.teks,/Halo https:\/\/www\.instagram\.com\/old\//);
console.log('uji-buletin-sosial: OK');
